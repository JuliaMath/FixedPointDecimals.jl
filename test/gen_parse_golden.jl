# Generates `test/data/parse_golden.tsv`, a corpus of `parse` outcomes used by
# `test/parse_api_tests.jl` as a regression (differential) test.
#
# The checked-in corpus was produced with FixedPointDecimals v0.6.5, whose parser was
# built on Parsers.jl v2. Regenerating it is only needed when the corpus itself changes:
#     julia --project test/gen_parse_golden.jl
using FixedPointDecimals
using FixedPointDecimals: RoundThrows
using Random

const TYPES = (Int8, UInt8, Int16, Int32, Int64, UInt64, Int128, UInt128)
const MODES = (RoundNearest => "N", RoundToZero => "Z", RoundThrows => "T")
const NSTRINGS = 4000
const NCOMBOS = 6

maxdigits(T) = ndigits(typemax(T))

function randdigits(rng, n)
    n == 0 && return ""
    # Bias towards interesting digits: lots of 0s and 9s, and a sprinkle of 5s for ties
    return String([rand(rng, (rand(rng, '0':'9'), '0', '9', '5')) for _ in 1:n])
end

# Mostly short digit runs, sometimes long enough to need UInt128 or UInt256 accumulators
randlen(rng) = rand(rng) < 0.8 ? rand(rng, 0:6) : rand(rng) < 0.7 ? rand(rng, 0:25) : rand(rng, 0:50)

function randinput(rng)
    r = rand(rng)
    io = IOBuffer()
    rand(rng) < 0.1 && print(io, rand(rng, (" ", "  ", "\t")))
    print(io, rand(rng, ("", "", "", "-", "+")))
    nint = rand(rng) < 0.1 ? 0 : randlen(rng)
    print(io, randdigits(rng, nint))
    if rand(rng) < 0.7
        print(io, '.')
        print(io, randdigits(rng, randlen(rng)))
    end
    if rand(rng) < 0.3
        print(io, rand(rng, ('e', 'E')), rand(rng, ("", "-", "+")))
        print(io, rand(rng) < 0.6 ? rand(rng, 0:5) : rand(rng) < 0.9 ? rand(rng, 0:45) : rand(rng, 0:500))
    end
    rand(rng) < 0.1 && print(io, rand(rng, (" ", "  ", "\t")))
    s = String(take!(io))
    if r < 0.08 && !isempty(s)
        # Corrupt the string with a junk character
        i = rand(rng, 1:length(s))
        c = rand(rng, ('.', 'e', '-', '+', ',', 'a', ' ', '\n', '\0', 'é', '_'))
        s = s[1:prevind(s, i)] * c * s[i:end]
    end
    return s
end

function outcome(::Type{FD}, s, mode) where {FD}
    try
        return string(parse(FD, s, mode).i)
    catch e
        e isa InexactError && return "Inexact"
        e isa OverflowError && return "Overflow"
        e isa ArgumentError && return "Argument"
        rethrow()
    end
end

function main(path)
    rng = Xoshiro(131)
    open(path, "w") do io
        println(io, "# type\tf\tmode\tinput (escaped)\toutcome  -- generated by test/gen_parse_golden.jl")
        for _ in 1:NSTRINGS
            s = randinput(rng)
            for _ in 1:NCOMBOS
                T = rand(rng, TYPES)
                f = rand(rng, (0, 1, 2, rand(rng, 0:maxdigits(T)-1), maxdigits(T) - 1))
                mode, mname = rand(rng, MODES)
                println(io, T, '\t', f, '\t', mname, '\t', escape_string(s), '\t', outcome(FixedDecimal{T,f}, s, mode))
            end
        end
    end
end

main(joinpath(@__DIR__, "data", "parse_golden.tsv"))
